const { transformArray } = require('./B');

describe('2267B. Fashionable Array', () => {
  it.each`
    n    | arr                         | result
    ${1} | ${[2, 3, 2]}                | ${[3, 2, 2]}
    ${2} | ${[4, 4, 2, 1, 3, 1]}       | ${[4, 4, 3, 2, 1, 1]}
    ${3} | ${[1, 3, 2, 4, 2]}          | ${[4, 3, 2, 1, 2]}
    ${4} | ${[1, 1, 1, 2]}             | ${[2, 1, 1, 1]}
    ${5} | ${[1, 2, 3, 4, 5, 6, 7]}    | ${[7, 6, 5, 4, 3, 2, 1]}
    ${6} | ${[1, 1, 4, 2, 3, 3, 3, 2]} | ${[4, 3, 2, 1, 3, 3, 2, 1]}
    ${7} | ${[4, 3, 3, 3, 2, 1, 4, 1]} | ${[4, 4, 3, 3, 2, 1, 1, 3]}
  `('Base test: $n', ({ arr, result }) => {
    expect(transformArray(arr)).toStrictEqual(result);
  });
});
