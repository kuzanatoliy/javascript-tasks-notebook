const { getScore } = require('./C');

describe('1969C. Minimizing the Sum', () => {
  it.each`
    n    | k    | a    | b    | cities                                                                                | result
    ${1} | ${2} | ${3} | ${5} | ${[[0, 0], [1, -2], [-2, 1], [-1, 3], [2, -2], [-3, -3]]}                             | ${4}
    ${2} | ${0} | ${1} | ${2} | ${[[-1000000000, -1000000000], [1000000000, 1000000000]]}                             | ${4000000000}
    ${3} | ${5} | ${4} | ${2} | ${[[154, 147], [-154, -147], [123, 456], [20, 23], [43, 20], [998, 244], [353, 100]]} | ${0}
    ${4} | ${1} | ${3} | ${1} | ${[[0, 10], [1, 20], [2, 30]]}                                                        | ${22}
    ${5} | ${3} | ${2} | ${4} | ${[[0, 0], [-100, 100], [-1, -1], [-1, 0]]}                                           | ${1}
  `('Base test: $n', ({ k, a, b, cities, result }) => {
    expect(getScore(k, a, b, cities)).toBe(result);
  });
});
