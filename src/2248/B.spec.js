const { isItPossibleToTransform } = require('./B');

describe('2248B. Merge to Match', () => {
  it.each`
    n     | arrA                         | arrB           | result
    ${1}  | ${[1, 3]}                    | ${[2]}         | ${'YES'}
    ${2}  | ${[1, 3, 5]}                 | ${[2, 4]}      | ${'NO'}
    ${3}  | ${[1, 3, 5, 7]}              | ${[4, 6]}      | ${'YES'}
    ${4}  | ${[2, 5, 8, 11]}             | ${[1, 10]}     | ${'NO'}
    ${5}  | ${[1, 4, 7, 9]}              | ${[3, 10]}     | ${'NO'}
    ${6}  | ${[10, 1, 100, 6, 4]}        | ${[90, 5]}     | ${'YES'}
    ${7}  | ${[1, 4, 0, 20, 30, 40]}     | ${[3, 15, 35]} | ${'YES'}
    ${8}  | ${[1, 2, 3, 100]}            | ${[4, 5]}      | ${'NO'}
    ${9}  | ${[1, 8, 3, 30, 18, 12, 25]} | ${[2, 15, 28]} | ${'YES'}
    ${10} | ${[1, 2, 3, 5]}              | ${[4]}         | ${'YES'}
    ${11} | ${[1, 3, 5, 6]}              | ${[2, 4]}      | ${'YES'}
  `('Base test: $n', ({ arrA, arrB, result }) => {
    expect(isItPossibleToTransform(arrA, arrB)).toBe(result);
  });
});
