const { transformNumber } = require('./B');

describe('1857B. Ten Words of Wisdom', () => {
  it.each`
    n    | snum                      | result
    ${1} | ${'1'}                    | ${'1'}
    ${2} | ${'5'}                    | ${'10'}
    ${3} | ${'99'}                   | ${'100'}
    ${4} | ${'913'}                  | ${'1000'}
    ${5} | ${'1980'}                 | ${'2000'}
    ${6} | ${'20444'}                | ${'20444'}
    ${7} | ${'20445'}                | ${'21000'}
    ${5} | ${'60947'}                | ${'100000'}
    ${6} | ${'419860'}               | ${'420000'}
    ${7} | ${'40862016542130810467'} | ${'41000000000000000000'}
  `('Base test: $n', ({ snum, result }) => {
    expect(transformNumber(snum)).toBe(result);
  });
});
