const { getNumbers } = require('./C');

describe('1872C. Non-coprime Split', () => {
  it.each`
    n     | a          | b           | result
    ${1}  | ${11}      | ${15}       | ${[2, 10]}
    ${2}  | ${1}       | ${3}        | ${[-1]}
    ${3}  | ${18}      | ${19}       | ${[2, 16]}
    ${4}  | ${41}      | ${43}       | ${[2, 40]}
    ${5}  | ${777}     | ${777}      | ${[3, 774]}
    ${6}  | ${8000000} | ${10000000} | ${[2, 7999998]}
    ${7}  | ${2000}    | ${2023}     | ${[2, 1998]}
    ${8}  | ${1791791} | ${1791791}  | ${[-1]}
    ${9}  | ${1}       | ${4}        | ${[2, 2]}
    ${10} | ${2}       | ${3}        | ${[-1]}
    ${11} | ${9840769} | ${9840769}  | ${[3137, 9837632]}
  `('Base test: $n', ({ a, b, result }) => {
    expect(getNumbers(a, b)).toStrictEqual(result);
  });
});
