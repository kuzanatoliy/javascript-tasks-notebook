const { getMaxSum } = require('./B');

describe('1920B. Summation Game', () => {
  it.each`
    n    | arr                                 | k    | x    | result
    ${1} | ${[1]}                              | ${1} | ${1} | ${0}
    ${2} | ${[3, 1, 2, 4]}                     | ${1} | ${1} | ${2}
    ${3} | ${[1, 4, 3, 2, 5, 6]}               | ${6} | ${3} | ${0}
    ${4} | ${[3, 7, 3, 3, 32, 15]}             | ${6} | ${1} | ${3}
    ${5} | ${[5, 5, 3, 3, 3, 2, 9, 9]}         | ${5} | ${3} | ${-5}
    ${6} | ${[1, 8, 2, 9, 3, 3, 4, 5, 3, 200]} | ${6} | ${4} | ${-9}
    ${7} | ${[4, 3]}                           | ${2} | ${1} | ${0}
    ${8} | ${[1, 3]}                           | ${1} | ${2} | ${-1}
  `('Base test: $n', ({ arr, k, x, result }) => {
    expect(getMaxSum(arr, k, x)).toBe(result);
  });
});
