const { restoreArray } = require('./C');

describe('1811A. Musical Puzzle', () => {
  it.each`
    n     | string              | result
    ${1}  | ${[3, 4, 4, 5]}     | ${[3, 3, 4, 4, 5]}
    ${2}  | ${[2, 2, 1]}        | ${[2, 2, 1, 1]}
    ${3}  | ${[0, 0, 0, 0]}     | ${[0, 0, 0, 0, 0]}
    ${4}  | ${[0, 3, 4, 4, 3]}  | ${[0, 0, 3, 4, 3, 3]}
    ${5}  | ${[10]}             | ${[10, 10]}
    ${6}  | ${[3, 3, 3]}        | ${[3, 3, 3, 3]}
    ${7}  | ${[4, 2, 5, 5]}     | ${[4, 2, 2, 5, 5]}
    ${8}  | ${[3, 3, 3]}        | ${[3, 3, 3, 3]}
    ${9}  | ${[2, 1, 0]}        | ${[2, 1, 0, 0]}
    ${10} | ${[4, 4]}           | ${[4, 4, 4]}
    ${11} | ${[8, 1, 3, 5, 10]} | ${[8, 1, 1, 3, 5, 10]}
  `('Base test: $n', ({ string, result }) => {
    expect(restoreArray(string)).toStrictEqual(result);
  });
});
