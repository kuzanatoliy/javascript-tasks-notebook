const { getMinOperationsCount } = require('./C');

describe('1759C. Thermostat', () => {
  it.each`
    n     | l      | r     | x     | a     | b     | result
    ${1}  | ${3}   | ${5}  | ${6}  | ${3}  | ${3}  | ${0}
    ${2}  | ${0}   | ${15} | ${5}  | ${4}  | ${5}  | ${2}
    ${3}  | ${0}   | ${10} | ${5}  | ${3}  | ${7}  | ${3}
    ${4}  | ${3}   | ${5}  | ${6}  | ${3}  | ${4}  | ${-1}
    ${5}  | ${-10} | ${10} | ${11} | ${-5} | ${6}  | ${1}
    ${6}  | ${-3}  | ${3}  | ${4}  | ${1}  | ${0}  | ${-1}
    ${7}  | ${-5}  | ${10} | ${8}  | ${9}  | ${2}  | ${3}
    ${8}  | ${1}   | ${5}  | ${1}  | ${2}  | ${5}  | ${1}
    ${9}  | ${-1}  | ${4}  | ${3}  | ${0}  | ${2}  | ${3}
    ${10} | ${-6}  | ${3}  | ${6}  | ${-1} | ${-4} | ${-1}
  `('Base test: $n', ({ l, r, x, a, b, result }) => {
    expect(getMinOperationsCount(l, r, x, a, b)).toBe(result);
  });
});
